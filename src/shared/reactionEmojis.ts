export function extractSingleEmoji(value: string): string | null {
  const trimmed = value.trim();

  if (!trimmed) {
    return null;
  }

  const segments = [...new Intl.Segmenter(undefined, { granularity: 'grapheme' }).segment(trimmed)].map(
    (part) => part.segment,
  );

  if (segments.length !== 1) {
    return null;
  }

  const emoji = segments[0];

  if (!/\p{Extended_Pictographic}/u.test(emoji)) {
    return null;
  }

  return emoji;
}
